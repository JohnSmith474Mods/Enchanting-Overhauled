package johnsmith.enchantingoverhauled.api.enchantment;

import johnsmith.enchantingoverhauled.Constants;
import johnsmith.enchantingoverhauled.menu.enchant.EnchantmentMenu;

import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.ByIdMap;

import java.util.Arrays;
import java.util.function.IntFunction;

/**
 * Defines the origin or source of an enchantment displayed in the custom Enchanting Altar GUI.
 * <p>
 * This enumeration is used by the {@link EnchantmentMenu} and its client-side widgets to distinguish
 * between the three potential actions when enchanting an item:
 * <ul>
 *   <li>{@link #TARGET}: Upgrading an existing enchantment directly on the item being enchanted.</li>
 *   <li>{@link #SOURCE}: Transferring an enchantment from a catalyst item (e.g., an Enchanted Book, Page, or Tome) in the source slot.</li>
 *   <li>{@link #TABLE}: Applying a new, randomly rolled enchantment generated by the enchanting altar.</li>
 * </ul>
 */
public enum EnchantmentSource {

    /**
     * Represents a null or uninitialized source (ID: {@code -1}).
     */
    NONE(-1, "none", 0, 0, 0),

    /**
     * The enchantment originated from the <b>Target</b> item itself (for upgrading existing enchantments) (ID: {@code 0}).
     */
    TARGET(0, "target", 0xFFFF80, 0, 0xFFFFFF),

    /**
     * The enchantment originated from the <b>Source</b> item (e.g., a Tome) in the dedicated source slot (for transferring enchantments) (ID: {@code 1}).
     */
    SOURCE(1, "source", 0, 0, 0xFFFFFF),

    /**
     * The enchantment is a <b>new</b> offering generated by the enchanting altar (ID: {@code 2}).
     */
    TABLE(2, "table", 0, 0, 0xFFFFFF);

    /**
     * The unique integer identifier used for network synchronization.
     */
    private final int id;

    /**
     * The internal string name of this source, used to construct texture paths.
     */
    public final String name;

    /**
     * The plain background texture used when the slot is enabled and affordable.
     */
    public final ResourceLocation enabledTexture;

    /**
     * The plain background texture used when the slot is hovered by the cursor.
     */
    public final ResourceLocation highlightedTexture;

    /**
     * The plain background texture used when the slot is disabled or unaffordable.
     */
    public final ResourceLocation disabledTexture;

    /**
     * The default text color when the slot is enabled.
     */
    public final int enabledColor;

    /**
     * The default text color when the slot is hovered.
     */
    public final int highlightedColor;

    /**
     * The default text color when the slot is disabled.
     */
    public final int disabledColor;

    /**
     * Constructs an {@code EnchantmentSource} with its visual metadata and unique integer identifier.
     *
     * @param id               The integer ID used for synchronization between server and client.
     * @param name             The string identifier used in button texture resource locations.
     * @param enabledColor     The RGB color for enabled button text.
     * @param highlightedColor The RGB color for highlighted button text.
     * @param disabledColor    The RGB color for disabled button text.
     */
    EnchantmentSource(
            final int id,
            final String name,
            final int enabledColor,
            final int highlightedColor,
            final int disabledColor
    ) {
        this.id = id;
        this.name = name;
        this.enabledTexture = ResourceLocation.fromNamespaceAndPath(
                Constants.MOD_ID,
                "textures/gui/container/enchanting_table/button/enabled/" + name + "_plain.png"
        );
        this.highlightedTexture = ResourceLocation.fromNamespaceAndPath(
                Constants.MOD_ID,
                "textures/gui/container/enchanting_table/button/highlighted/" + name + "_plain.png"
        );
        this.disabledTexture = ResourceLocation.fromNamespaceAndPath(
                Constants.MOD_ID,
                "textures/gui/container/enchanting_table/button/disabled/" + name + "_plain.png"
        );
        this.enabledColor = enabledColor;
        this.highlightedColor = highlightedColor;
        this.disabledColor = disabledColor;
    }

    /**
     * Resolves the numbered variant texture for an enabled enchantment button of this source type.
     *
     * @param variant The deterministic texture variant index (typically {@code 0} through {@code 9}).
     * @return The {@link ResourceLocation} of the enabled button texture variant.
     */
    public ResourceLocation getEnabledTexture(int variant) {
        return ResourceLocation.fromNamespaceAndPath(
                Constants.MOD_ID,
                "textures/gui/container/enchanting_table/button/enabled/" + name + "_" + variant + ".png"
        );
    }

    /**
     * Resolves the numbered variant texture for a highlighted (hovered) enchantment button of this source type.
     *
     * @param variant The deterministic texture variant index (typically {@code 0} through {@code 9}).
     * @return The {@link ResourceLocation} of the highlighted button texture variant.
     */
    public ResourceLocation getHighlightedTexture(int variant) {
        return ResourceLocation.fromNamespaceAndPath(
                Constants.MOD_ID,
                "textures/gui/container/enchanting_table/button/highlighted/" + name + "_" + variant + ".png"
        );
    }

    /**
     * Resolves the numbered variant texture for a disabled enchantment button of this source type.
     *
     * @param variant The deterministic texture variant index (typically {@code 0} through {@code 9}).
     * @return The {@link ResourceLocation} of the disabled button texture variant.
     */
    public ResourceLocation getDisabledTexture(int variant) {
        return ResourceLocation.fromNamespaceAndPath(
                Constants.MOD_ID,
                "textures/gui/container/enchanting_table/button/disabled/" + name + "_" + variant + ".png"
        );
    }

    /**
     * Retrieves the integer ID of this source type.
     *
     * @return The unique integer ID.
     */
    public int getId() {
        return id;
    }

    /**
     * An efficient lookup function built using {@link ByIdMap} for all valid, non-negative source IDs.
     * {@link #NONE} ({@code -1}) is explicitly excluded from this map construction.
     */
    private static final IntFunction<EnchantmentSource> BY_ID = ByIdMap.continuous(
            EnchantmentSource::getId,
            Arrays.stream(values()).filter(v -> v.id >= 0).toArray(EnchantmentSource[]::new),
            ByIdMap.OutOfBoundsStrategy.WRAP
    );

    /**
     * Retrieves the {@code EnchantmentSource} enum constant matching the given integer ID.
     *
     * @param id The integer ID to look up.
     * @return The corresponding {@code EnchantmentSource} constant, or {@link #NONE} if the ID is {@code -1}.
     */
    public static EnchantmentSource byId(int id) {
        if (id == -1) return NONE;
        return BY_ID.apply(id);
    }
}